#!/usr/bin/env bash
# BOBA Bear PostgreSQL entrypoint wrapper (IMP-037).
#
# Preserves upstream docker-entrypoint.sh behaviour for the non-root image
# USER (postgres / UID 999). Build-time root installation stays in the
# Dockerfile. This process must not run as uid 0, must not escalate, and
# must not chown or otherwise repair a mounted data directory.
#
# When BOBA_PGBACKREST_ARCHIVE=1, render a concrete /etc/pgbackrest/pgbackrest.conf
# BEFORE PostgreSQL can fire archive_command. Archive-push uses that same file.
# Heavy scheduled backups remain outside this path and use host-local flock;
# WAL archival must never wait on that lock.
#
# Production-shaped mode (default) fail-closes unless physical Spaces config is
# present. Disposable local tests must set BOBA_PGBACKREST_REPO_MODE=posix.
# Secrets stay in the environment. They are never written into config files
# and never logged.
set -euo pipefail

if [ "$(id -u)" = "0" ]; then
  echo "BOBA postgres: refusing to start as root (non-root runtime contract)" >&2
  exit 1
fi

ARCHIVE_ENABLED="${BOBA_PGBACKREST_ARCHIVE:-0}"
ARCHIVE_TIMEOUT="${BOBA_PGBACKREST_ARCHIVE_TIMEOUT:-300}"
STANZA="${BOBA_PGBACKREST_STANZA:-boba}"
CONFIG_PATH="${BOBA_PGBACKREST_CONFIG_PATH:-/etc/pgbackrest/pgbackrest.conf}"
ARCHIVE_CONF_DIR="${BOBA_PGBACKREST_ARCHIVE_CONF_DIR:-/etc/postgresql}"
RENDER_BIN="${BOBA_PGBACKREST_RENDER_BIN:-/usr/local/bin/boba-render-pgbackrest-conf}"
RUN_DIR="${BOBA_POSTGRES_RUN_DIR:-/var/run/postgresql}"
REPO_DIR="${BOBA_PGBACKREST_LIB_DIR:-/var/lib/pgbackrest}"
LOG_DIR="${BOBA_PGBACKREST_LOG_DIR:-/var/log/pgbackrest}"
SPOOL_DIR="${BOBA_PGBACKREST_SPOOL_DIR:-/var/spool/pgbackrest}"
PGDATA_PATH="${PGDATA:-/var/lib/postgresql/18/docker}"

require_already_writable_dir() {
  local dir="$1"
  if [ ! -d "${dir}" ] || [ ! -w "${dir}" ]; then
    echo "BOBA postgres: directory is not already writable by the non-root runtime: ${dir}" >&2
    exit 1
  fi
}

# Fail closed before the official entrypoint can create or chmod PGDATA.
# Walk up to the first existing ancestor so a fresh, correctly owned mount of
# /var/lib/postgresql is accepted and a wrong-UID mount is left untouched.
require_postgres_data_writable() {
  local probe="${PGDATA_PATH}"
  while [ ! -e "${probe}" ]; do
    local parent
    parent="$(dirname "${probe}")"
    if [ "${parent}" = "${probe}" ]; then
      echo "BOBA postgres: PGDATA ${PGDATA_PATH} is not available to the non-root runtime; refusing to repair ownership" >&2
      exit 1
    fi
    probe="${parent}"
  done
  local owner
  owner="$(stat -c %u "${probe}")"
  if [ ! -d "${probe}" ] || [ ! -w "${probe}" ] || [ "${owner}" != "$(id -u)" ]; then
    echo "BOBA postgres: PGDATA ${PGDATA_PATH} is not writable by uid $(id -u) (found ${probe} owned by uid ${owner}); refusing to repair ownership" >&2
    exit 1
  fi
}

starting_postgres=0
if [ "${1:-}" = "postgres" ] || [ "${1:-}" = "docker-entrypoint.sh" ]; then
  starting_postgres=1
fi

if [ "${ARCHIVE_ENABLED}" = "1" ]; then
  if [ ! -x "${RENDER_BIN}" ]; then
    echo "BOBA pgBackRest: ${RENDER_BIN} missing; refusing to start with archive_command" >&2
    exit 1
  fi
  if ! rendered="$("${RENDER_BIN}")"; then
    echo "BOBA pgBackRest: concrete config render failed; refusing to start PostgreSQL" >&2
    exit 1
  fi
  if [ -z "${rendered}" ]; then
    echo "BOBA pgBackRest: rendered config is empty; refusing to start PostgreSQL" >&2
    exit 1
  fi

  require_already_writable_dir "$(dirname "${CONFIG_PATH}")"
  require_already_writable_dir "${ARCHIVE_CONF_DIR}"
  require_already_writable_dir "${REPO_DIR}"
  require_already_writable_dir "${LOG_DIR}"
  require_already_writable_dir "${SPOOL_DIR}"

  umask 077
  printf '%s\n' "${rendered}" > "${CONFIG_PATH}"
  chmod 640 "${CONFIG_PATH}"
  umask 022

  # Map host-local secrets into pgBackRest env names for archive-push children.
  # Prefer compose service environment (PGBACKREST_REPO1_*) so compose-exec
  # backups inherit the same authority without relying solely on PID1 exports.
  # Do not write secrets into the conf file and do not print them.
  if [ -z "${PGBACKREST_REPO1_CIPHER_PASS:-}" ] && [ -n "${PGBACKREST_CIPHER_PASS:-}" ]; then
    export PGBACKREST_REPO1_CIPHER_PASS="${PGBACKREST_CIPHER_PASS}"
  fi
  if [ "${BOBA_PGBACKREST_REPO_MODE:-s3}" != "posix" ] && [ "${BOBA_PGBACKREST_REPO_MODE:-s3}" != "local" ]; then
    if [ -z "${PGBACKREST_REPO1_S3_KEY:-}" ] && [ -n "${BOBA_PHYSICAL_SPACES_ACCESS_KEY_ID:-}" ]; then
      export PGBACKREST_REPO1_S3_KEY="${BOBA_PHYSICAL_SPACES_ACCESS_KEY_ID}"
    fi
    if [ -z "${PGBACKREST_REPO1_S3_KEY_SECRET:-}" ] && [ -n "${BOBA_PHYSICAL_SPACES_SECRET_ACCESS_KEY:-}" ]; then
      export PGBACKREST_REPO1_S3_KEY_SECRET="${BOBA_PHYSICAL_SPACES_SECRET_ACCESS_KEY}"
    fi
  fi

  ARCHIVE_CMD="pgbackrest --config=${CONFIG_PATH} --stanza=${STANZA} archive-push %p"
  cat > "${ARCHIVE_CONF_DIR}/boba-archive.conf" <<EOF
# Generated by boba-postgres-entrypoint (IMP-037). Do not edit by hand.
archive_mode = on
archive_timeout = ${ARCHIVE_TIMEOUT}
archive_command = '${ARCHIVE_CMD}'
EOF
  chmod 640 "${ARCHIVE_CONF_DIR}/boba-archive.conf"

  if [ "${starting_postgres}" = "1" ]; then
    set -- "$@" -c "archive_mode=on" \
      -c "archive_timeout=${ARCHIVE_TIMEOUT}" \
      -c "archive_command=${ARCHIVE_CMD}"
  fi
fi

if [ "${starting_postgres}" = "1" ]; then
  require_already_writable_dir "${RUN_DIR}"
  require_postgres_data_writable
fi

if [ -n "${BOBA_DOCKER_ENTRYPOINT:-}" ]; then
  exec "${BOBA_DOCKER_ENTRYPOINT}" "$@"
fi
if [ -x /usr/local/bin/docker-entrypoint.sh ]; then
  exec /usr/local/bin/docker-entrypoint.sh "$@"
fi
exec docker-entrypoint.sh "$@"
