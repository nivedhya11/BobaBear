#!/usr/bin/env bash
# BOBA Bear PostgreSQL C1 non-root entrypoint (disposable proof / PG-C1).
#
# Runs entirely as the image USER (postgres / UID 999). Does not escalate,
# does not chown volume trees, and does not repair host ownership.
# When BOBA_PGBACKREST_ARCHIVE=1, renders concrete pgBackRest config before
# archive_command can fire (same contract as production wrapper).
set -euo pipefail

if [ "$(id -u)" = "0" ]; then
  echo "BOBA C1 postgres: refusing to start as root (C1 non-root contract)" >&2
  exit 1
fi

ARCHIVE_ENABLED="${BOBA_PGBACKREST_ARCHIVE:-0}"
ARCHIVE_TIMEOUT="${BOBA_PGBACKREST_ARCHIVE_TIMEOUT:-300}"
STANZA="${BOBA_PGBACKREST_STANZA:-boba}"
CONFIG_PATH="${BOBA_PGBACKREST_CONFIG_PATH:-/etc/pgbackrest/pgbackrest.conf}"
ARCHIVE_CONF_DIR="${BOBA_PGBACKREST_ARCHIVE_CONF_DIR:-/etc/postgresql}"
RENDER_BIN="${BOBA_PGBACKREST_RENDER_BIN:-/usr/local/bin/boba-render-pgbackrest-conf}"

require_writable_dir() {
  local dir="$1"
  if [ ! -d "${dir}" ]; then
    mkdir -p "${dir}" || {
      echo "BOBA C1 postgres: cannot create writable dir ${dir}" >&2
      exit 1
    }
  fi
  if [ ! -w "${dir}" ]; then
    echo "BOBA C1 postgres: directory not writable by non-root runtime: ${dir}" >&2
    exit 1
  fi
}

if [ "${ARCHIVE_ENABLED}" = "1" ]; then
  if [ ! -x "${RENDER_BIN}" ]; then
    echo "BOBA C1 pgBackRest: ${RENDER_BIN} missing; refusing archive_mode start" >&2
    exit 1
  fi
  require_writable_dir "$(dirname "${CONFIG_PATH}")"
  require_writable_dir "${ARCHIVE_CONF_DIR}"
  require_writable_dir /var/lib/pgbackrest
  require_writable_dir /var/log/pgbackrest
  require_writable_dir /var/spool/pgbackrest

  if ! rendered="$("${RENDER_BIN}")"; then
    echo "BOBA C1 pgBackRest: concrete config render failed; refusing start" >&2
    exit 1
  fi
  if [ -z "${rendered}" ]; then
    echo "BOBA C1 pgBackRest: rendered config empty; refusing start" >&2
    exit 1
  fi
  umask 077
  printf '%s\n' "${rendered}" > "${CONFIG_PATH}"
  chmod 640 "${CONFIG_PATH}"
  umask 022

  if [ -z "${PGBACKREST_REPO1_CIPHER_PASS:-}" ] && [ -n "${PGBACKREST_CIPHER_PASS:-}" ]; then
    export PGBACKREST_REPO1_CIPHER_PASS="${PGBACKREST_CIPHER_PASS}"
  fi
  if [ "${BOBA_PGBACKREST_REPO_MODE:-s3}" != "posix" ] && [ "${BOBA_PGBACKREST_REPO_MODE:-s3}" != "local" ]; then
    if [ -z "${PGBACKREST_REPO1_S3_KEY:-}" ] && [ -n "${BOBA_PHYSICAL_SPACES_ACCESS_KEY_ID:-}" ]; then
      export PGBACKREST_REPO1_S3_KEY="${BOBA_PHYSICAL_SPACES_ACCESS_KEY_ID}"
    fi
    if [ -z "${PGBACKREST_REPO1_S3_KEY_SECRET:-}" ] && [ -n "${BOBA_PHYSICAL_SPACES_SECRET_ACCESS_KEY:-}" ]; then
      export PGBACKREST_REPO1_S3_KEY_SECRET="${BOBA_PHYSICAL_SPACES_SECRET_ACCESS_KEY}"
    fi
  fi

  ARCHIVE_CMD="pgbackrest --config=${CONFIG_PATH} --stanza=${STANZA} archive-push %p"
  cat > "${ARCHIVE_CONF_DIR}/boba-archive.conf" <<EOF
# Generated by boba-postgres-c1-entrypoint (PG-C1 proof). Do not edit by hand.
archive_mode = on
archive_timeout = ${ARCHIVE_TIMEOUT}
archive_command = '${ARCHIVE_CMD}'
EOF
  chmod 640 "${ARCHIVE_CONF_DIR}/boba-archive.conf"

  if [ "${1:-}" = "postgres" ] || [ "${1:-}" = "docker-entrypoint.sh" ]; then
    set -- "$@" -c "archive_mode=on" \
      -c "archive_timeout=${ARCHIVE_TIMEOUT}" \
      -c "archive_command=${ARCHIVE_CMD}"
  fi
fi

if [ -x /usr/local/bin/docker-entrypoint.sh ]; then
  exec /usr/local/bin/docker-entrypoint.sh "$@"
fi
exec docker-entrypoint.sh "$@"
